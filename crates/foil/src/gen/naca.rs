    #[test]
    fn xfoil_sections_are_unchanged() {
        for code in ["2412", "0012", "23012", "4415", "0009", "12"] {
            let s = parse(code).unwrap();
            let f = s.generate().unwrap();
            let ides: i32 = code.parse().unwrap();
            let r = if ides <= 9999 { naca4(ides, NSIDE) } else { naca5(ides, NSIDE).unwrap() };
            assert_eq!(f.x, r.0[1..=r.2].to_vec());
            assert_eq!(f.y, r.1[1..=r.2].to_vec());
            assert_eq!(f.name, format!("NACA {code}"));
        }
    }

    #[test]
    fn closed_trailing_edge_closes() {
        let f = parse("0012 closed TE").unwrap().generate().unwrap();
        let n = f.n();
        assert!((f.y[0] - f.y[n - 1]).abs() < 1e-5, "{} {}", f.y[0], f.y[n - 1]);
        let open = parse("0012").unwrap().generate().unwrap();
        assert!((open.y[0] - open.y[open.n() - 1]).abs() > 2e-3);
    }

    #[test]
    fn six_series_reaches_its_thickness() {
        for fam in SixFamily::ALL {
            for t in [0.06, 0.12, 0.21] {
                let form = SixForm::new(fam, t).unwrap();
                let x: Vec<f64> = (0..=400).map(|i| i as f64 / 400.0).collect();
                let yt = form.half_thickness(&x).unwrap();
                let tmax = 2.0 * yt.iter().cloned().fold(0.0, f64::max);
                assert!((tmax - t).abs() < 2e-5, "{} {t}: {tmax}", fam.label());
                assert!(yt[0].abs() < 1e-12 && yt[400].abs() < 1e-6, "{} {t}: ends {} {}", fam.label(), yt[0], yt[400]);
            }
        }
    }

    #[test]
    fn reflexed_mean_line_has_zero_moment() {
        // thin-airfoil Cm about c/4 of the mean line: (1/2) int (dy/dx)(cos 2th - cos th) dth
        for p in [0.10, 0.15, 0.20, 0.25] {
            let n = 20000;
            let mut cm = 0.0;
            for k in 0..n {
                let th = PI * (k as f64 + 0.5) / n as f64;
                let x = 0.5 * (1.0 - th.cos());
                let (_, s) = mean_line_at(MeanLine::FiveDigitReflex { cl: 0.3, p }, x);
                cm += 0.5 * s * ((2.0 * th).cos() - th.cos()) * PI / n as f64;
            }
            assert!(cm.abs() < 2e-3, "p {p}: cm {cm}");
            // and the standard line has a clearly negative one
            let mut cms = 0.0;
            for k in 0..n {
                let th = PI * (k as f64 + 0.5) / n as f64;
                let x = 0.5 * (1.0 - th.cos());
                let (_, s) = mean_line_at(MeanLine::FiveDigit { cl: 0.3, p }, x);
                cms += 0.5 * s * ((2.0 * th).cos() - th.cos()) * PI / n as f64;
            }
            assert!(cms < -0.005, "p {p}: standard cm {cms}");
        }
    }

