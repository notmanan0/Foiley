//! NACA airfoil families: 4-digit, 5-digit (standard and reflexed, any design
//! lift coefficient), 4-digit modified, 16-series, 6-series and 6A-series.
//!
//! Every family is built the way its NACA report defines it: a thickness
//! distribution laid off perpendicular to a mean line (Abbott & von
//! Doenhoff, eq. 6.1).  The equations, constants and the 6-series conformal
//! mapping follow NASA TM-4741 (Ladson, Brooks, Hill and Sproles, 1996) as
//! revised in Ralph Carmichael's public-domain NACA456 (AIAA 2001-5235).
//!
//! The 4-digit and 210-250 5-digit codes that XFoil's own `NACA` command
//! accepts keep XFoil's geometry (thickness added vertically, XFoil's point
//! spacing), so foils generated by earlier versions, saved projects and
//! polar hashes do not change.

use super::{naca6_data, spline, NSIDE};
use crate::{Foil, FoilError};
use foiley::geom::{naca4, naca5};
use std::f64::consts::PI;

/// The eight NACA 6- and 6A-series thickness families.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum SixFamily {
    S63,
    S64,
    S65,
    S66,
    S67,
    A63,
    A64,
    A65,
}

impl SixFamily {
    pub const ALL: [SixFamily; 8] = [SixFamily::S63, SixFamily::S64, SixFamily::S65, SixFamily::S66, SixFamily::S67, SixFamily::A63, SixFamily::A64, SixFamily::A65];

    fn index(self) -> usize {
        self as usize
    }
    /// "63", "64A", ...
    pub fn label(self) -> &'static str {
        ["63", "64", "65", "66", "67", "63A", "64A", "65A"][self.index()]
    }
    /// A-series (straight aft surfaces, used with the modified a=0.8 mean line).
    pub fn is_a(self) -> bool {
        self.index() >= 5
    }
    fn from_digit(d: u32, a_series: bool) -> Option<SixFamily> {
        use SixFamily::*;
        Some(match (d, a_series) {
            (3, false) => S63,
            (4, false) => S64,
            (5, false) => S65,
            (6, false) => S66,
            (7, false) => S67,
            (3, true) => A63,
            (4, true) => A64,
            (5, true) => A65,
            _ => return None,
        })
    }
    /// NACA456 `ScaleFactor`: polynomial in t/c giving the starting scale of
    /// the epsilon and psi functions.
    fn scale_guess(self, t: f64) -> f64 {
        const C: [[f64; 5]; 8] = [
            [0.0, 8.1827699, 1.3776209, -0.092851684, 7.5942563],
            [0.0, 4.6535511, 1.038063, -1.5041794, 4.7882784],
            [0.0, 6.5718716, 0.49376292, 0.7319794, 1.9491474],
            [0.0, 6.7581414, 0.19253769, 0.81282621, 0.85202897],
            [0.0, 6.627289, 0.098965859, 0.96759774, 0.90537584],
            [0.0, 8.1845925, 1.0492569, 1.31150930, 4.4515579],
            [0.0, 8.2125018, 0.76855961, 1.4922345, 3.6130133],
            [0.0, 8.2514822, 0.46569361, 1.50113018, 2.0908904],
        ];
        C[self.index()].iter().rev().fold(0.0, |acc, c| acc * t + c)
    }
}

/// Thickness distribution.  `t` is the maximum thickness / chord.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Thickness {
    /// NACA 4-digit; `closed_te` uses -0.1036 for the x^4 coefficient
    /// instead of -0.1015, which closes the trailing edge.
    FourDigit { t: f64, closed_te: bool },
    /// NACA 4-digit modified: leading-edge radius index and position of
    /// maximum thickness (x/c).
    FourDigitModified { t: f64, le_index: f64, x_max: f64 },
    /// NACA 6- or 6A-series, from the conformal mapping of a circle.
    SixSeries { family: SixFamily, t: f64 },
}

/// Mean (camber) line.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum MeanLine {
    Symmetric,
    /// NACA 4-digit (two parabolas): maximum camber `m` at `p` (x/c).
    FourDigit { m: f64, p: f64 },
    /// NACA 5-digit (3-digit mean line): design lift coefficient `cl`,
    /// maximum camber at `p` (x/c).
    FiveDigit { cl: f64, p: f64 },
    /// NACA 5-digit reflexed (zero pitching moment about c/4).
    FiveDigitReflex { cl: f64, p: f64 },
    /// NACA 6-series a-type mean line: uniform load from the leading edge
    /// to x/c = `a`, then decreasing linearly to zero at the trailing edge.
    SixSeries { a: f64, cl: f64 },
    /// The modified a=0.8 mean line of the 6A-series (straight aft of
    /// x/c = 0.86).
    SixA { cl: f64 },
}

/// A parsed NACA designation.
#[derive(Clone, Debug, PartialEq)]
pub struct NacaSection {
    /// Canonical designation without the "NACA" prefix ("64A010",
    /// "63(2)-415 a=0.5", "2412 closed TE").
    pub designation: String,
    pub thickness: Thickness,
    pub mean_line: MeanLine,
    /// 4-digit or 210-250 5-digit codes generated by XFoil's own routine.
    xfoil_code: Option<i32>,
}

/// Where the straight aft surfaces of the 6A-series begin (x/c).
const A_STRAIGHT_FROM: f64 = 0.82;

fn bad(code: &str, why: &str) -> FoilError {
    FoilError::Parse(format!("NACA '{}': {why}", code.trim()))
}

fn digits(s: &str) -> Option<Vec<u32>> {
    (!s.is_empty() && s.chars().all(|c| c.is_ascii_digit())).then(|| s.chars().map(|c| c.to_digit(10).unwrap()).collect())
}

/// The part of a foil name after "NACA" ("NACA 64A010" -> "64A010"), if
/// the name starts with NACA (any case, with or without a space or dash).
pub fn strip_naca_prefix(name: &str) -> Option<&str> {
    let t = name.trim();
    if t.len() < 4 || !t.is_char_boundary(4) || !t[..4].eq_ignore_ascii_case("naca") {
        return None;
    }
    let rest = t[4..].trim_start_matches([' ', '-', '_']).trim();
    (!rest.is_empty()).then_some(rest)
}

/// Parse a NACA designation (with or without the "NACA" prefix):
///
/// * `2412`, `0012` - 4-digit
/// * `23012`, `23112`, `43012` - 5-digit: first digit 0.15 x design CL,
///   second twice the position of maximum camber (tenths of chord... in
///   twentieths), third 0 standard or 1 reflexed, last two t/c percent
/// * `0012-64`, `2412-63` - 4-digit modified: LE radius index, position of
///   maximum thickness in tenths
/// * `16-212` - 16-series: design CL in tenths, t/c percent
/// * `63-206`, `64(2)-415`, `65_2-415`, `652-415`, `63-412 a=0.5` -
///   6-series (subscript = low-drag range, kept in the name only; default
///   mean line a = 1.0)
/// * `64A010`, `63A210` - 6A-series with the modified a=0.8 mean line
///
/// A trailing `closed TE` closes the trailing edge of a 4-digit thickness
/// (4- and 5-digit sections).
pub fn parse(code: &str) -> Result<NacaSection, FoilError> {
    let upper = code.trim().to_ascii_uppercase();
    let mut s: String = match strip_naca_prefix(&upper) {
        Some(r) => r.to_string(),
        None => upper.clone(),
    };
    let mut closed_te = false;
    let mut a: Option<f64> = None;
    loop {
        let t = s.trim_end().trim_end_matches(',').trim_end().to_string();
        if let Some(r) = t.strip_suffix("CLOSED TE").or_else(|| t.strip_suffix("CLOSED-TE")).or_else(|| t.strip_suffix("CLOSEDTE")) {
            closed_te = true;
            s = r.to_string();
            continue;
        }
        if let Some(pos) = t.rfind("A=") {
            let v: f64 = t[pos + 2..].trim().parse().map_err(|_| bad(code, "the mean line must be given as a=<number between 0 and 1>"))?;
            if !(0.0..=1.0).contains(&v) {
                return Err(bad(code, "the mean-line parameter a must be between 0 and 1"));
            }
            a = Some(v);
            s = t[..pos].to_string();
            continue;
        }
        s = t;
        break;
    }
    let body: String = s.chars().filter(|c| !c.is_whitespace()).collect();
    if body.is_empty() {
        return Err(bad(code, "no designation"));
    }
    let only_six = |what: &str| -> Result<(), FoilError> {
        if a.is_some() {
            return Err(bad(code, &format!("a= applies to 6-series sections only, not {what}")));
        }
        Ok(())
    };
    let closed_suffix = if closed_te { " closed TE" } else { "" };

    // 4-digit (1-4 digits, as XFoil accepts "12" for 0012)
    if let Some(d) = digits(&body).filter(|d| d.len() <= 4) {
        only_six("4-digit sections")?;
        let ides: i32 = body.parse().unwrap();
        let d4: Vec<u32> = std::iter::repeat_n(0, 4 - d.len()).chain(d).collect();
        let m = d4[0] as f64 / 100.0;
        let p = d4[1] as f64 / 10.0;
        let t = (d4[2] * 10 + d4[3]) as f64 / 100.0;
        if m > 0.0 && p == 0.0 {
            return Err(bad(code, "a cambered 4-digit section needs a position of maximum camber (second digit 1-9)"));
        }
        let mean_line = if m == 0.0 { MeanLine::Symmetric } else { MeanLine::FourDigit { m, p } };
        if closed_te {
            check_t(code, t, 0.5)?;
        }
        return Ok(NacaSection {
            designation: if closed_te { format!("{}{}{}{}{closed_suffix}", d4[0], d4[1], d4[2], d4[3]) } else { body.clone() },
            thickness: Thickness::FourDigit { t, closed_te },
            mean_line,
            xfoil_code: (!closed_te).then_some(ides),
        });
    }

    // 5-digit
    if let Some(d) = digits(&body).filter(|d| d.len() == 5) {
        only_six("5-digit sections")?;
        let (l, p, q) = (d[0], d[1], d[2]);
        let t = (d[3] * 10 + d[4]) as f64 / 100.0;
        if l == 0 {
            return Err(bad(code, "the first digit (design CL / 0.15) must be 1-9"));
        }
        let cl = 0.15 * l as f64;
        let pos = p as f64 / 20.0;
        let mean_line = match q {
            0 if (1..=5).contains(&p) => MeanLine::FiveDigit { cl, p: pos },
            1 if (2..=5).contains(&p) => MeanLine::FiveDigitReflex { cl, p: pos },
            0 => return Err(bad(code, "the second digit of a 5-digit section (twice the position of maximum camber) must be 1-5")),
            1 => return Err(bad(code, "reflexed 5-digit mean lines are defined for second digits 2-5 (221 to 251)")),
            _ => return Err(bad(code, "the third digit of a 5-digit section must be 0 (standard) or 1 (reflexed)")),
        };
        check_t(code, t, 0.5)?;
        let legacy = l == 2 && q == 0 && !closed_te;
        return Ok(NacaSection {
            designation: format!("{body}{closed_suffix}"),
            thickness: Thickness::FourDigit { t, closed_te },
            mean_line,
            xfoil_code: legacy.then(|| body.parse().unwrap()),
        });
    }
    if closed_te {
        return Err(bad(code, "'closed TE' applies to the 4-digit thickness of 4- and 5-digit sections only"));
    }

    // 4-digit modified: MPTT-IJ
    if let Some((head, tail)) = body.split_once('-') {
        if let (Some(h), Some(tl)) = (digits(head).filter(|d| d.len() == 4), digits(tail).filter(|d| d.len() == 2)) {
            only_six("4-digit modified sections")?;
            let m = h[0] as f64 / 100.0;
            let p = h[1] as f64 / 10.0;
            let t = (h[2] * 10 + h[3]) as f64 / 100.0;
            if m > 0.0 && p == 0.0 {
                return Err(bad(code, "a cambered section needs a position of maximum camber (second digit 1-9)"));
            }
            if !(2..=6).contains(&tl[1]) {
                return Err(bad(code, "the position of maximum thickness (last digit) must be 2-6 (tenths of chord)"));
            }
            check_t(code, t, 0.4)?;
            return Ok(NacaSection {
                designation: body.clone(),
                thickness: Thickness::FourDigitModified { t, le_index: tl[0] as f64, x_max: tl[1] as f64 / 10.0 },
                mean_line: if m == 0.0 { MeanLine::Symmetric } else { MeanLine::FourDigit { m, p } },
                xfoil_code: None,
            });
        }
        // 16-series: 16-CTT
        if head == "16" {
            let d = digits(tail).filter(|d| d.len() == 3).ok_or_else(|| bad(code, "a 16-series section is written 16-CTT (design CL in tenths, t/c percent)"))?;
            if a.is_some_and(|a| a != 1.0) {
                return Err(bad(code, "16-series sections always use the a=1.0 mean line"));
            }
            let cl = d[0] as f64 / 10.0;
            let t = (d[1] * 10 + d[2]) as f64 / 100.0;
            check_t(code, t, 0.4)?;
            return Ok(NacaSection {
                designation: body.clone(),
                thickness: Thickness::FourDigitModified { t, le_index: 4.0, x_max: 0.5 },
                mean_line: if cl == 0.0 { MeanLine::Symmetric } else { MeanLine::SixSeries { a: 1.0, cl } },
                xfoil_code: None,
            });
        }
    }

    // 6- and 6A-series
    let mut ch = body.chars();
    if ch.next() == Some('6') {
        let fam_digit = ch.next().and_then(|c| c.to_digit(10)).ok_or_else(|| bad(code, "unrecognised designation"))?;
        let rest: String = ch.collect();
        if let Some(r) = rest.strip_prefix('A') {
            let family = SixFamily::from_digit(fam_digit, true).ok_or_else(|| bad(code, "6A-series thickness forms exist for 63A, 64A and 65A"))?;
            if a.is_some() {
                return Err(bad(code, "6A-series sections always use the modified a=0.8 mean line"));
            }
            let r = r.strip_prefix('-').unwrap_or(r);
            let d = digits(r).filter(|d| d.len() == 3).ok_or_else(|| bad(code, "a 6A-series section is written 6xACTT (design CL in tenths, t/c percent), e.g. 64A010"))?;
            let cl = d[0] as f64 / 10.0;
            let t = (d[1] * 10 + d[2]) as f64 / 100.0;
            check_t(code, t, 0.3)?;
            return Ok(NacaSection {
                designation: format!("{}{}{}{}", family.label(), d[0], d[1], d[2]),
                thickness: Thickness::SixSeries { family, t },
                mean_line: if cl == 0.0 { MeanLine::Symmetric } else { MeanLine::SixA { cl } },
                xfoil_code: None,
            });
        }
        let family = SixFamily::from_digit(fam_digit, false).ok_or_else(|| bad(code, "6-series thickness forms exist for 63 to 67"))?;
        let (sub, tail) = rest.split_once('-').ok_or_else(|| bad(code, "a 6-series section is written 6x-CTT or 6x(n)-CTT, e.g. 63-206 or 64(2)-415"))?;
        let subscript = if sub.is_empty() {
            None
        } else if let Some(inner) = sub.strip_prefix('(').and_then(|s| s.strip_suffix(')')) {
            Some(digits(inner).ok_or_else(|| bad(code, "the subscript in parentheses must be digits"))?.iter().map(|d| char::from_digit(*d, 10).unwrap()).collect::<String>())
        } else {
            let s = sub.strip_prefix('_').or_else(|| sub.strip_prefix(',')).unwrap_or(sub);
            let d = digits(s).filter(|d| d.len() == 1).ok_or_else(|| bad(code, "the low-drag-range subscript must be one digit"))?;
            Some(d[0].to_string())
        };
        let d = digits(tail).filter(|d| d.len() == 3).ok_or_else(|| bad(code, "the part after the dash must be three digits: design CL in tenths, t/c percent"))?;
        let cl = d[0] as f64 / 10.0;
        let t = (d[1] * 10 + d[2]) as f64 / 100.0;
        check_t(code, t, 0.3)?;
        let mut designation = family.label().to_string();
        if let Some(s) = &subscript {
            designation.push_str(&format!("({s})"));
        }
        designation.push_str(&format!("-{}{}{}", d[0], d[1], d[2]));
        let a = a.unwrap_or(1.0);
        if a != 1.0 {
            designation.push_str(&format!(" a={a}"));
        }
        return Ok(NacaSection {
            designation,
            thickness: Thickness::SixSeries { family, t },
            mean_line: if cl == 0.0 { MeanLine::Symmetric } else { MeanLine::SixSeries { a, cl } },
            xfoil_code: None,
        });
    }
    Err(bad(code, "not a supported designation (4-digit 2412, 5-digit 23012/23112, 4-digit modified 0012-64, 16-series 16-212, 6-series 63-206, 6A-series 64A010)"))
}

fn check_t(code: &str, t: f64, max: f64) -> Result<(), FoilError> {
    if t <= 0.0 || t > max {
        return Err(bad(code, &format!("thickness {:.0}% is outside 1-{:.0}% for this family", t * 100.0, max * 100.0)));
    }
    Ok(())
}

impl NacaSection {
    pub fn name(&self) -> String {
        format!("NACA {}", self.designation)
    }

    /// Whether XFoil's own NACA routine generates this section (bit-identical
    /// to Foiley 1.1 and to XFoil's `NACA` command).
    pub fn is_xfoil_section(&self) -> bool {
        self.xfoil_code.is_some()
    }

    /// Half-thickness at each chord station.
    pub fn half_thickness(&self, x: &[f64]) -> Result<Vec<f64>, FoilError> {
        let mut yt = self.raw_half_thickness(x)?;
        if let Some(y0) = self.a_series_anchor()? {
            for (y, &xi) in yt.iter_mut().zip(x) {
                if xi > A_STRAIGHT_FROM {
                    *y = y0 * (1.0 - xi) / (1.0 - A_STRAIGHT_FROM);
                }
            }
        }
        Ok(yt)
    }

    /// Mapped thickness at x/c = 0.82, where the straight aft surfaces of a
    /// 6A-series section start.
    fn a_series_anchor(&self) -> Result<Option<f64>, FoilError> {
        match self.thickness {
            Thickness::SixSeries { family, .. } if family.is_a() => Ok(Some(self.raw_half_thickness(&[A_STRAIGHT_FROM])?[0])),
            _ => Ok(None),
        }
    }

    fn raw_half_thickness(&self, x: &[f64]) -> Result<Vec<f64>, FoilError> {
        Ok(match self.thickness {
            Thickness::FourDigit { t, closed_te } => {
                let a4 = if closed_te { -0.1036 } else { -0.1015 };
                x.iter().map(|&x| if x <= 0.0 { 0.0 } else { 5.0 * t * (0.2969 * x.sqrt() + x * (-0.1260 + x * (-0.3516 + x * (0.2843 + x * a4)))) }).collect()
            }
            Thickness::FourDigitModified { t, le_index, x_max } => four_digit_modified(t, le_index, x_max, x),
            Thickness::SixSeries { family, t } => SixForm::new(family, t)?.half_thickness(x)?,
        })
    }

    /// Mean-line ordinate and slope at each chord station.
    pub fn mean_line(&self, x: &[f64]) -> Vec<(f64, f64)> {
        x.iter().map(|&x| mean_line_at(self.mean_line, x)).collect()
    }

    /// Upper and lower surface points (leading edge to trailing edge) at the
    /// chord stations `x`, with the thickness perpendicular to the mean line.
    pub fn surfaces_at(&self, x: &[f64]) -> Result<super::Surfaces, FoilError> {
        let combine = |xi: f64, yt: f64| {
            let (yc, slope) = mean_line_at(self.mean_line, xi);
            let (s, c) = slope.atan().sin_cos();
            ((xi - yt * s, yc + yt * c), (xi + yt * s, yc - yt * c))
        };
        // 6A-series: aft of x/c = 0.82 both surfaces are straight lines to
        // the trailing edge (NASA NACA6, after NACA Report 903)
        let anchor = self.a_series_anchor()?.map(|y0| combine(A_STRAIGHT_FROM, y0));
        let yt = self.raw_half_thickness(x)?;
        let mut up = Vec::with_capacity(x.len());
        let mut lo = Vec::with_capacity(x.len());
        for (i, &xi) in x.iter().enumerate() {
            let (mut u, mut l) = combine(xi, yt[i]);
            if let (Some((au, al)), true) = (anchor, xi > A_STRAIGHT_FROM) {
                u.1 = au.1 * (1.0 - u.0) / (1.0 - au.0);
                l.1 = al.1 * (1.0 - l.0) / (1.0 - al.0);
            }
            up.push(u);
            lo.push(l);
        }
        Ok((up, lo))
    }

    /// Generate the section (239 points, as `Foil::naca` always has).
    pub fn generate(&self) -> Result<Foil, FoilError> {
        let mut f = if let Some(ides) = self.xfoil_code {
            let _q = foiley::quiet_scope();
            let r = if ides <= 9999 { Some(naca4(ides, NSIDE)) } else { naca5(ides, NSIDE) };
            let (xb, yb, nb, _) = r.ok_or_else(|| FoilError::Parse(format!("NACA {} is not a supported designation", self.designation)))?;
            Foil::new(self.name(), xb[1..=nb].to_vec(), yb[1..=nb].to_vec())?
        } else {
            let x = super::nose_spacing(NSIDE);
            let (up, lo) = self.surfaces_at(&x)?;
            super::from_surfaces(self.name(), &up, &lo)?
        };
        f.note = format!("NACA {} generated", self.designation);
        Ok(f)
    }
}

// ------------------------------------------------------------- mean lines

fn mean_line_at(ml: MeanLine, x: f64) -> (f64, f64) {
    match ml {
        MeanLine::Symmetric => (0.0, 0.0),
        MeanLine::FourDigit { m, p } => {
            if x < p {
                (m / (p * p) * (2.0 * p * x - x * x), 2.0 * m / (p * p) * (p - x))
            } else {
                let q = 1.0 - p;
                (m / (q * q) * ((1.0 - 2.0 * p) + 2.0 * p * x - x * x), 2.0 * m / (q * q) * (p - x))
            }
        }
        MeanLine::FiveDigit { cl, p } => {
            let (r, k1) = five_digit_constants(p);
            let f = k1 * cl / 1.8;
            if x < r {
                (f * x * (x * (x - 3.0 * r) + r * r * (3.0 - r)), f * (3.0 * x * (x - 2.0 * r) + r * r * (3.0 - r)))
            } else {
                (f * r * r * r * (1.0 - x), -f * r * r * r)
            }
        }
        MeanLine::FiveDigitReflex { cl, p } => {
            let (r, k1) = five_digit_reflex_constants(p);
            // k2/k1 for zero pitching moment (NACA Report 537, p. 522)
            let k21 = (3.0 * (r - p).powi(2) - r * r * r) / (1.0 - r).powi(3);
            let (r3, mr3) = (r * r * r, (1.0 - r).powi(3));
            let f = k1 * cl / 1.8;
            if x < r {
                (f * ((x - r).powi(3) - k21 * mr3 * x - x * r3 + r3), f * (3.0 * (x - r).powi(2) - k21 * mr3 - r3))
            } else {
                (f * (k21 * (x - r).powi(3) - k21 * mr3 * x - x * r3 + r3), f * (3.0 * k21 * (x - r).powi(2) - k21 * mr3 - r3))
            }
        }
        MeanLine::SixSeries { a, cl } => a_mean_line(a, cl, x),
        MeanLine::SixA { cl } => {
            // NACA Report 903, p. 210: a=0.8 line scaled by 0.97948, straight
            // with slope -0.24521 CL from x/c = 0.86 to the trailing edge.
            let te_slope = -0.24521 * cl;
            if x > 0.86 {
                return (te_slope * (x - 1.0), te_slope);
            }
            a_mean_line(0.8, cl * 0.97948, x)
        }
    }
}

/// r (end of the cubic) and k1 of the standard 3-digit mean line,
/// tabulated for CL = 0.3 (Abbott & von Doenhoff, p. 115).
fn five_digit_constants(p: f64) -> (f64, f64) {
    const P: [f64; 5] = [0.05, 0.10, 0.15, 0.20, 0.25];
    const R: [f64; 5] = [0.0580, 0.1260, 0.2025, 0.2900, 0.3910];
    const K1: [f64; 5] = [361.4, 51.64, 15.957, 6.643, 3.230];
    let i = P.iter().position(|&v| (v - p).abs() < 1e-9).expect("tabulated 5-digit camber position");
    (R[i], K1[i])
}

/// r and k1 of the reflexed 3-digit mean line (NASA TM-4741, p. 8).
#[allow(clippy::approx_constant)] // 0.318 is NACA's tabulated r, not 1/pi
fn five_digit_reflex_constants(p: f64) -> (f64, f64) {
    const P: [f64; 4] = [0.10, 0.15, 0.20, 0.25];
    const R: [f64; 4] = [0.1300, 0.2170, 0.3180, 0.4410];
    const K1: [f64; 4] = [51.99, 15.793, 6.520, 3.191];
    let i = P.iter().position(|&v| (v - p).abs() < 1e-9).expect("tabulated reflexed camber position");
    (R[i], K1[i])
}

/// NACA a-type mean line (Abbott & von Doenhoff, eq. 4-26 and 4-27).
fn a_mean_line(a: f64, cl: f64, x: f64) -> (f64, f64) {
    const EPS: f64 = 1e-7;
    let omx = 1.0 - x;
    if x < EPS || omx < EPS {
        return (0.0, 0.0);
    }
    let oma = 1.0 - a;
    if oma.abs() < EPS {
        let y = -(omx * omx.ln() + x * x.ln()) * cl * (0.25 / PI);
        let s = (omx.ln() - x.ln()) * cl * (0.25 / PI);
        return (y, s);
    }
    let (g, h) = if a.abs() < EPS {
        (-0.25, -0.5)
    } else {
        let g = -(a * a * (0.5 * a.ln() - 0.25) + 0.25) / oma;
        (g, g + (0.5 * oma * oma * oma.ln() - 0.25 * oma * oma) / oma)
    };
    let amx = a - x;
    let (t1, t1p) = if amx.abs() < EPS { (0.0, 0.0) } else { (amx * amx * (2.0 * amx.abs().ln() - 1.0), -amx * amx.abs().ln()) };
    let t2 = omx * omx * (1.0 - 2.0 * omx.ln());
    let t2p = omx * omx.ln();
    let k = cl / (2.0 * PI * (a + 1.0));
    let y = 0.25 * (t1 + t2) / oma - x * x.ln() + g - h * x;
    let s = (t1p + t2p) / oma - 1.0 - x.ln() - h;
    (k * y, k * s)
}

// ---------------------------------------------------------- thickness

/// NACA 4-digit modified thickness (Abbott & von Doenhoff, p. 117; NACA456
/// `Thickness4M`).
fn four_digit_modified(t: f64, le_index: f64, xm: f64, x: &[f64]) -> Vec<f64> {
    // d1 (trailing-edge slope) for the position of maximum thickness
    // (Abbott & von Doenhoff, p. 117); NACA456's quartic fit in between
    const D1: [(f64, f64); 5] = [(0.2, 0.200), (0.3, 0.234), (0.4, 0.315), (0.5, 0.465), (0.6, 0.700)];
    let d1 = D1.iter().find(|(m, _)| (m - xm).abs() < 1e-9).map(|p| p.1).unwrap_or_else(|| [3.48e-5, 2.3076628, -10.127712, 19.961478, -10.420597].iter().rev().fold(0.0, |acc, c| acc * xm + c));
    let rle = 1.1019 / 36.0 * (t * le_index).powi(2);
    let a0 = (0.2 / t) * (2.0 * rle).sqrt();
    let omxm = 1.0 - xm;
    let a3 = 0.1 / (xm * xm * xm) + (d1 * omxm - 0.294) / (xm * omxm * omxm) - (3.0 / 8.0) * a0 / xm.powf(2.5);
    let a2 = -0.1 / (xm * xm) + 0.5 * a0 / (xm * xm * xm).sqrt() - 2.0 * a3 * xm;
    let a1 = -0.5 * a0 / xm.sqrt() - 2.0 * a2 * xm - 3.0 * a3 * xm * xm;
    let d3 = (3.0 * d1 - 0.588 / omxm) / (3.0 * omxm * omxm);
    let d2 = -1.5 * omxm * d3 - 0.5 * d1 / omxm;
    let d0 = 0.002;
    x.iter()
        .map(|&x| {
            let y = if x <= 0.0 {
                0.0
            } else if x < xm {
                a0 * x.sqrt() + x * (a1 + x * (a2 + x * a3))
            } else {
                let u = 1.0 - x;
                d0 + u * (d1 + u * (d2 + u * d3))
            };
            5.0 * t * y
        })
        .collect()
}

/// A 6-series thickness form: the conformal map of a circle through the
/// scaled epsilon and psi functions, splined around the contour.
struct SixForm {
    s: Vec<f64>,
    x: Vec<f64>,
    y: Vec<f64>,
    xp: Vec<f64>,
    yp: Vec<f64>,
}

/// (x, half-thickness) of the 201 mapped points (leading to trailing edge)
/// for epsilon and psi scaled by `sf` (NACA456 `SetSixDigitPoints`).
fn six_points(family: SixFamily, sf: f64) -> (Vec<f64>, Vec<f64>) {
    let eps = &naca6_data::EPS[family.index()];
    let psi = &naca6_data::PSI[family.index()];
    let zeta = |i: usize| {
        let phi = PI * i as f64 / 200.0;
        let r = (sf * psi[i]).exp();
        let th = phi - sf * eps[i];
        ((r + 1.0 / r) * th.cos(), (r - 1.0 / r) * th.sin())
    };
    let z0 = zeta(0);
    let zn = zeta(200);
    let d = ((zn.0 - z0.0).powi(2) + (zn.1 - z0.1).powi(2)).sqrt();
    (0..201)
        .map(|i| {
            let z = zeta(i);
            ((z0.0 - z.0) / d, (z.1 - z0.1) / d)
        })
        .unzip()
}

/// Maximum of the tabulated half-thickness, refined by a parabola through
/// the three points around the peak.
fn peak(y: &[f64]) -> f64 {
    let (i, _) = y.iter().enumerate().fold((0, f64::MIN), |b, (i, &v)| if v > b.1 { (i, v) } else { b });
    if i == 0 || i + 1 >= y.len() {
        return y[i];
    }
    let (a, b, c) = (y[i - 1], y[i], y[i + 1]);
    let den = a - 2.0 * b + c;
    if den >= 0.0 {
        return b;
    }
    let d = 0.5 * (a - c) / den;
    b - 0.25 * (a - c) * d
}

impl SixForm {
    fn new(family: SixFamily, t: f64) -> Result<SixForm, FoilError> {
        // NACA456 starts from a fitted scale factor; like NASA's NACA6 we
        // then iterate the scale until the maximum thickness is t exactly.
        let mut sf = family.scale_guess(t);
        let (mut xt, mut yt) = six_points(family, sf);
        for _ in 0..50 {
            let ratio = t / (2.0 * peak(&yt));
            if !ratio.is_finite() || ratio <= 0.0 {
                return Err(FoilError::Geometry(format!("NACA {} thickness form does not reach t/c {t}", family.label())));
            }
            if (ratio - 1.0).abs() < 1e-12 {
                break;
            }
            sf *= ratio;
            (xt, yt) = six_points(family, sf);
        }
        if (2.0 * peak(&yt) - t).abs() > 1e-9 || xt.windows(2).any(|w| w[1] <= w[0]) {
            return Err(FoilError::Geometry(format!("NACA {} thickness form could not be scaled to t/c {t}", family.label())));
        }
        // contour from the trailing edge over the upper side to the leading
        // edge and back along the lower side (NACA456 ParametrizeAirfoil)
        let mut x: Vec<f64> = xt.iter().rev().cloned().collect();
        let mut y: Vec<f64> = yt.iter().rev().cloned().collect();
        x.extend_from_slice(&xt[1..]);
        y.extend(yt[1..].iter().map(|v| -v));
        let mut s = vec![0.0; x.len()];
        for k in 1..x.len() {
            s[k] = s[k - 1] + ((x[k] - x[k - 1]).powi(2) + (y[k] - y[k - 1]).powi(2)).sqrt();
        }
        let xp = spline::fmm_slopes(&s, &x);
        let yp = spline::fmm_slopes(&s, &y);
        Ok(SixForm { s, x, y, xp, yp })
    }

    fn half_thickness(&self, xs: &[f64]) -> Result<Vec<f64>, FoilError> {
        let lo = 200;
        let (s, x, xp) = (&self.s[lo..], &self.x[lo..], &self.xp[lo..]);
        xs.iter()
            .map(|&xc| {
                let xc = xc.clamp(0.0, 1.0);
                let u = spline::solve(s, x, xp, xc).ok_or_else(|| FoilError::Geometry(format!("6-series thickness: no point at x/c {xc}")))?;
                // the closed trailing edge can come out as -1e-12
                Ok((-spline::eval(&self.s, &self.y, &self.yp, u).0).max(0.0))
            })
            .collect()
    }
}

